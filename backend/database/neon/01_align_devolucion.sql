-- Nivelación de postventa.devolucion (y cambio_producto) en la BD compartida de Neon (si2_22026).
-- Ejecutar manualmente en conexión directa (sin -pooler), con respaldo previo.
-- No mezclar con las migraciones locales TypeORM de backend/src/database/migrations/.

BEGIN;

-- 1. Autoincremento (IDENTITY) en devolucion y cambio_producto
ALTER TABLE postventa.devolucion
  ALTER COLUMN id_devolucion ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE postventa.cambio_producto
  ALTER COLUMN id_cambio ADD GENERATED BY DEFAULT AS IDENTITY;

-- Sincronizar secuencia de cambio_producto por si ya tuviera filas
SELECT setval(
  pg_get_serial_sequence('postventa.cambio_producto', 'id_cambio'),
  COALESCE((SELECT MAX(id_cambio) FROM postventa.cambio_producto), 0) + 1,
  false
);

-- 2. Restricciones acordadas con Inventario en postventa.devolucion
ALTER TABLE postventa.devolucion
  ALTER COLUMN id_reclamo SET NOT NULL,
  ALTER COLUMN id_producto SET NOT NULL,
  ALTER COLUMN cantidad SET NOT NULL;

ALTER TABLE postventa.devolucion
  ADD CONSTRAINT chk_devolucion_cantidad CHECK (cantidad > 0),
  ADD CONSTRAINT uq_devolucion_caso UNIQUE (id_reclamo);

-- 3. Columnas de HU-06 en postventa.devolucion (transparentes para Inventario)
ALTER TABLE postventa.devolucion
  ADD COLUMN IF NOT EXISTS id_detalle_ped integer NOT NULL
    REFERENCES ecommerce_ventas.ecom_detalle_pedido(id_detalle_ped) ON DELETE RESTRICT,
  ADD COLUMN IF NOT EXISTS fecha_devolucion date NOT NULL,
  ADD COLUMN IF NOT EXISTS motivo text NOT NULL
    CHECK (length(trim(motivo)) BETWEEN 1 AND 2000);

ALTER TABLE postventa.devolucion
  ADD CONSTRAINT fk_devolucion_producto_caso
    FOREIGN KEY (id_reclamo, id_detalle_ped)
    REFERENCES postventa.registro_producto(id_reclamo, id_detalle_ped)
    ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS ix_devolucion_linea
  ON postventa.devolucion(id_detalle_ped);

COMMIT;
