import { QueryRunner } from 'typeorm';

export async function ensureSharedSchema(runner: QueryRunner): Promise<void> {
  const required: Record<string, string[]> = {
    venta: ['id_venta', 'id_pedido'], pedido: ['id_pedido', 'id_cliente'],
    cliente: ['id_cliente', 'nombre'],
    detalle_pedido: ['id_detalle_ped', 'id_pedido', 'id_producto'],
    inv_producto: ['id_producto', 'nombre_set'],
  };
  for (const [name, columns] of Object.entries(required)) {
    const table = await runner.getTable(name);
    if (!table || columns.some((column) => !table.findColumnByName(column))) {
      throw new Error(`Falta la estructura compartida ${name}. Carga primero el SQL acordado del ERP.`);
    }
  }
}

export async function ensureCaseTable(runner: QueryRunner): Promise<void> {
  if (!await runner.hasTable('reclamo')) {
    await runner.query(`CREATE TABLE reclamo (
      id_reclamo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_venta integer NOT NULL, id_cliente integer NOT NULL,
      motivo varchar(2000) NOT NULL CHECK (length(trim(motivo)) > 0),
      estado varchar(20) NOT NULL DEFAULT 'Abierto'
    )`);
  }
  const table = await runner.getTable('reclamo');
  if (!table || ['id_reclamo', 'id_venta', 'id_cliente', 'motivo', 'estado']
    .some((column) => !table.findColumnByName(column))) {
    throw new Error('La tabla reclamo no coincide con el esquema acordado. No se modificaron los datos.');
  }
  await runner.query('LOCK TABLE reclamo IN SHARE ROW EXCLUSIVE MODE');
  const id = table.findColumnByName('id_reclamo');
  if (!id?.isGenerated && !id?.default) {
    await runner.query('CREATE SEQUENCE postventa_reclamo_id_seq AS integer OWNED BY reclamo.id_reclamo');
    await runner.query("ALTER TABLE reclamo ALTER COLUMN id_reclamo SET DEFAULT nextval('postventa_reclamo_id_seq')");
  }
  for (const [column, parent, parentId] of [
    ['id_venta', 'venta', 'id_venta'], ['id_cliente', 'cliente', 'id_cliente'],
  ]) {
    const existing = table.foreignKeys.find((key) => key.columnNames.includes(column));
    if (existing && (existing.referencedTableName.split('.').pop() !== parent ||
      !existing.referencedColumnNames.includes(parentId))) {
      throw new Error(`La referencia ${column} de reclamo no coincide con el esquema acordado.`);
    }
    if (!existing) {
      await runner.query(`ALTER TABLE reclamo ADD CONSTRAINT fk_reclamo_${parent}
        FOREIGN KEY (${column}) REFERENCES ${parent}(${parentId}) ON DELETE RESTRICT`);
    }
  }
}

export async function copyLegacyRequests(runner: QueryRunner): Promise<void> {
  const invalid: { count: string }[] = await runner.query(`
    SELECT count(*) FROM peticion old
    LEFT JOIN venta v ON v.id_venta = old.id_venta
    LEFT JOIN pedido p ON p.id_pedido = v.id_pedido
    WHERE p.id_cliente IS DISTINCT FROM old.id_cliente OR EXISTS (
      SELECT 1 FROM detalle_peticion item
      LEFT JOIN detalle_pedido d ON d.id_detalle_ped = item.id_detalle_pedido
      WHERE item.id_peticion = old.id_peticion
        AND d.id_pedido IS DISTINCT FROM v.id_pedido
    )
  `);
  if (Number(invalid[0].count)) {
    throw new Error('Hay solicitudes anteriores sin correspondencia en el ERP. Deben conciliarse antes de migrar.');
  }
  await runner.query(`INSERT INTO reclamo(id_reclamo, id_venta, id_cliente, motivo, estado)
    SELECT id_peticion, id_venta, id_cliente, motivo, estado FROM peticion`);
  await runner.query(`INSERT INTO postventa_registro(id_reclamo, tipo, fecha_registro)
    SELECT id_peticion, tipo, fecha_reclamo FROM peticion`);
  await runner.query(`INSERT INTO postventa_registro_producto(id_reclamo, id_detalle_ped)
    SELECT id_peticion, id_detalle_pedido FROM detalle_peticion`);
  await runner.query(`SELECT setval(pg_get_serial_sequence('reclamo', 'id_reclamo'),
    GREATEST(COALESCE((SELECT max(id_reclamo) FROM reclamo), 0) + 1,
    nextval(pg_get_serial_sequence('reclamo', 'id_reclamo'))), false)`);
}
